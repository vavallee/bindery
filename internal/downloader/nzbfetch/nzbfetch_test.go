// realNZB is the shape every indexer returns on success: an XML declaration,
// the newzBin DOCTYPE, and an <nzb> root.
const realNZB = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE nzb PUBLIC "-//newzBin//DTD NZB 1.1//EN" "http://www.newzbin.com/DTD/nzb/nzb-1.1.dtd">
<!-- generated by the indexer -->
<nzb xmlns="http://www.newzbin.com/DTD/2003/nzb">
<head><meta type="category">Audio &gt; Audiobook - DE</meta></head>
</nzb>`

// plainTextErrorBody is the #2105 shape: three prolog-legal lines followed by
// plain text on line 4. Served with HTTP 200, it reaches SAB, which reports
// `xml.etree.ElementTree.ParseError: syntax error: line 4, column 0` — an
// error that names SAB for a response the indexer got wrong.
const plainTextErrorBody = "\n\n\nYou have reached your download limit for today.\n"

func TestValidateNZB_AcceptsNZBDocument(t *testing.T) {
	err := ValidateNZB("https://indexer.example.com/getnzb?id=1",
		&http.Response{StatusCode: 200, Request: endedAt(t, "https://indexer.example.com/getnzb?id=1")},
		[]byte(realNZB))
	if err != nil {
		t.Fatalf("a real NZB must be accepted, got: %v", err)
	}
}

// A UTF-8 BOM in front of the declaration is legal and some indexers emit one.
// Rejecting it would turn a working grab into a hard failure.
func TestValidateNZB_AcceptsNZBWithUTF8BOM(t *testing.T) {
	body := append([]byte("\xef\xbb\xbf"), []byte(realNZB)...)
	err := ValidateNZB("https://indexer.example.com/getnzb",
		&http.Response{StatusCode: 200, Request: endedAt(t, "https://indexer.example.com/getnzb")},
		body)
	if err != nil {
		t.Fatalf("a BOM-prefixed NZB must be accepted, got: %v", err)
	}
}

// A non-UTF-8 declared encoding must not read as "not an NZB" either: only the
// root element name decides, and that is ASCII in every encoding an indexer
// plausibly uses.
func TestValidateNZB_AcceptsNZBWithNonUTF8Declaration(t *testing.T) {
	body := []byte(`<?xml version="1.0" encoding="ISO-8859-1"?>` + "\n" + `<nzb xmlns="http://www.newzbin.com/DTD/2003/nzb"></nzb>`)
	err := ValidateNZB("https://indexer.example.com/getnzb",
		&http.Response{StatusCode: 200, Request: endedAt(t, "https://indexer.example.com/getnzb")},
		body)
	if err != nil {
		t.Fatalf("an ISO-8859-1 NZB must be accepted, got: %v", err)
	}
}

