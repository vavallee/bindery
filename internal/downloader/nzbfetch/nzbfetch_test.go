// bzip2NZB is a bzip2-compressed minimal NZB. Go's stdlib decompresses bzip2
// but cannot produce it, so the fixture is embedded rather than built here.
const bzip2NZB = "QlpoMTFBWSZTWYGv0DkAAA/fgAAQUAP4V4UABgA+593QIABoRTagAxDZQGnpAAaoZGhgRoAAaaeo" +
	"yN+FNosEHLTy84GaiI23SCfBABtTrNAysBurFOfLAEAu7kQ8Hf1AYxLXW6hJCM1jjeqUIg5IaRnv" +
	"gKkaHpkn/F3JFOFCQga/QOQ="

func gzipped(t *testing.T, payload string) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := gzip.NewWriter(&buf)
	if _, err := zw.Write([]byte(payload)); err != nil {
		t.Fatalf("gzip write: %v", err)
	}
	if err := zw.Close(); err != nil {
		t.Fatalf("gzip close: %v", err)
	}
	return buf.Bytes()
}

// Some newznab indexers serve the NZB as a gzip *file* — Content-Type
// application/x-gzip with no Content-Encoding — which the HTTP transport does
// not unwrap. Both download clients sniff the magic and decompress it
// themselves (SABnzbd's process_single_nzb: "Supports NZB, NZB.BZ2, NZB.GZ and
// GZ.NZB-in-disguise"), so rejecting those bytes would break a grab that works
// today. That is a worse outcome than the bug this validation fixes.
func TestValidateNZB_AcceptsGzippedNZB(t *testing.T) {
	err := ValidateNZB("https://indexer.example.com/getnzb",
		&http.Response{StatusCode: 200, Request: endedAt(t, "https://indexer.example.com/getnzb")}, gzipped(t, realNZB))
	if err != nil {
		t.Fatalf("a gzipped NZB must be accepted, got: %v", err)
	}
}

// Same argument as gzip: SAB names NZB.BZ2 in the formats it accepts, so a
// bzip2 body must not be rejected either.
func TestValidateNZB_AcceptsBzip2NZB(t *testing.T) {
	body, err := base64.StdEncoding.DecodeString(bzip2NZB)
	if err != nil {
		t.Fatalf("decode fixture: %v", err)
	}
	if err := ValidateNZB("https://indexer.example.com/getnzb",
		&http.Response{StatusCode: 200, Request: endedAt(t, "https://indexer.example.com/getnzb")}, body); err != nil {
		t.Fatalf("a bzip2 NZB must be accepted, got: %v", err)
	}
}

// Unwrapping the archive must not become a blanket "compressed means valid":
// the point of the check is the content, and a compressed error page is still
// an error page.
func TestValidateNZB_RejectsGzippedErrorPage(t *testing.T) {
	err := ValidateNZB("https://indexer.example.com/getnzb",
		&http.Response{StatusCode: 200, Request: endedAt(t, "https://indexer.example.com/getnzb")},
		gzipped(t, "You have reached your download limit for today."))
	if err == nil {
		t.Fatal("a gzipped error page must be rejected")
	}
	if msg := err.Error(); !strings.Contains(msg, "reached your download limit") {
		t.Errorf("error should quote the decompressed body: %s", msg)
	}
}

// A body that claims to be an archive and isn't must not have its raw bytes
// dumped into the error message — that is unreadable in a log and in the
// download row.
func TestValidateNZB_RejectsCorruptCompressedBody(t *testing.T) {
	body := append([]byte{0x1f, 0x8b}, []byte{0x00, 0xff, 0xfe, 0x01, 0x02}...)
	err := ValidateNZB("https://indexer.example.com/getnzb",
		&http.Response{StatusCode: 200, Request: endedAt(t, "https://indexer.example.com/getnzb")}, body)
	if err == nil {
		t.Fatal("a corrupt archive must be rejected")
	}
	msg := err.Error()
	if !strings.Contains(msg, "could not be decompressed") {
		t.Errorf("error should name the decompression failure: %s", msg)
	}
	if strings.ContainsRune(msg, '\xfe') {
		t.Errorf("raw archive bytes must not reach the message: %q", msg)
	}
}

// Expanding a compressed body to find the root element must be bounded, or a
// decompression bomb turns a validation check into an allocation attack.
func TestValidateNZB_DecompressionIsBounded(t *testing.T) {
	err := ValidateNZB("https://indexer.example.com/getnzb",
		&http.Response{StatusCode: 200, Request: endedAt(t, "https://indexer.example.com/getnzb")},
		gzipped(t, strings.Repeat("a", 256<<20)))
	if err == nil {
		t.Fatal("a body with no NZB root must be rejected however large it expands")
	}
}

// An empty 200 used to render as "…is not an NZB: " with nothing after the
// colon, which reads like the message itself was truncated.
func TestValidateNZB_EmptyBodyHasItsOwnMessage(t *testing.T) {
	err := ValidateNZB("https://indexer.example.com/getnzb",
		&http.Response{StatusCode: 200, Request: endedAt(t, "https://indexer.example.com/getnzb")}, nil)
	if err == nil {
		t.Fatal("an empty body must be rejected")
	}
	msg := err.Error()
	if !strings.Contains(msg, "empty body") {
		t.Errorf("empty body needs its own phrasing, got: %s", msg)
	}
	if strings.HasSuffix(msg, ": ") || strings.Contains(msg, "is not an NZB: ") {
		t.Errorf("message must not trail off after a colon: %q", msg)
	}
}
